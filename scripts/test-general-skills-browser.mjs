import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const out = path.resolve('artifacts/general-skills-20261117/verification');
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true, baseURL: 'http://127.0.0.1:5190' });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const skillName = '中文文稿制作';
const evidence = { skillName, errors };
try {
  await page.goto('http://127.0.0.1:5190/agent.html#skills');
  await page.getByRole('button', { name: '添加技能', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles(path.resolve('artifacts/general-skills-20261117/examples/office-presentation.zip'));
  await expect(page.getByText('检查通过', { exact: true })).toBeVisible({ timeout: 15000 });
  await page.getByLabel('技能名称', { exact: true }).fill(skillName);
  await expect(page.getByLabel('用途与适用范围')).not.toHaveValue('');
  const dialogBounds = await page.locator('.governance-dialog').boundingBox();
  expect(dialogBounds.x).toBeGreaterThan(100);
  expect(Math.abs(dialogBounds.x + dialogBounds.width / 2 - 720)).toBeLessThan(2);
  evidence.uploadCentered = true;
  await page.screenshot({ path: path.join(out, 'upload-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(out, 'upload-mobile.png') });
  evidence.uploadOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(evidence.uploadOverflow).toBe(false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '保存资产信息', exact: true }).click();
  await page.getByRole('button', { name: '申请审核', exact: true }).click();
  await page.getByLabel('审核意见').fill('已验证普通技能输入、脚本和中文文稿输出。');
  await page.getByRole('button', { name: '记录业务通过', exact: true }).click();
  await page.getByRole('button', { name: '技术审核', exact: true }).click();
  await page.getByLabel('安全检查', { exact: true }).selectOption('pass');
  await page.getByLabel('运行兼容', { exact: true }).selectOption('pass');
  await page.getByLabel('审核意见').fill('本机包检查、依赖检查与受限执行测试通过。');
  await page.getByRole('button', { name: '记录技术通过', exact: true }).click();
  await page.getByRole('button', { name: '上架可调用版本', exact: true }).click();
  await expect(page.getByText('该版本已上架，可按调用权限在对话中选择。')).toBeVisible();
  await page.getByLabel('关闭详情', { exact: true }).click();
  await page.getByRole('button', { name: skillName, exact: true }).click();
  await page.getByRole('button', { name: '选择技能', exact: true }).click();
  await expect(page.locator('.composer-skill-label')).toContainText(skillName);
  await page.locator('.composer textarea').fill('用所选技能制作2页中文PPT，主题“通用技能应用”，第一页介绍文稿生成，第二页介绍表格汇总。只作功能说明，不编造业务数据，直接生成可下载pptx，无需追问。');
  const responsePromise = page.waitForResponse(r => r.url().endsWith('/api/local/runs') && r.request().method() === 'POST');
  await page.getByLabel('发送消息', { exact: true }).click();
  const started = await (await responsePromise).json();
  evidence.taskId = started.taskId;
  evidence.runId = started.runId;
  console.log(JSON.stringify({ stage: 'run-started', runId: started.runId, taskId: started.taskId }));
  let run;
  for (let index = 0; index < 610; index++) {
    run = await (await page.request.get(`/api/local/runs/${started.runId}`)).json();
    if (run.status !== 'running') break;
    await page.waitForTimeout(1000);
  }
  expect(run.status).toBe('completed');
  evidence.tools = run.events.filter(item => item.kind === 'tool').map(item => item.data);
  const card = page.locator('.result-card').filter({ hasText: '.pptx' }).last();
  await expect(card).toBeVisible({ timeout: 10000 });
  await card.click();
  const frame = page.locator('.skill-artifact-frame');
  await expect(frame).toBeVisible({ timeout: 30000 });
  await expect(frame).toHaveAttribute('src', /^blob:/);
  await page.screenshot({ path: path.join(out, 'artifact-desktop.png'), fullPage: true });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: '下载文件' }).click();
  const download = await downloadPromise;
  evidence.downloadName = download.suggestedFilename();
  const saved = path.join(out, 'browser-' + download.suggestedFilename());
  await download.saveAs(saved);
  expect((await fs.stat(saved)).size).toBeGreaterThan(1000);
  evidence.slideCount = Number(execFileSync(path.resolve('apps/agno-service/.venv/bin/python'), ['-c', 'from pptx import Presentation; import sys; print(len(Presentation(sys.argv[1]).slides))', saved], { encoding: 'utf8' }).trim());
  expect(evidence.slideCount).toBe(2);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(frame).toBeVisible();
  await page.screenshot({ path: path.join(out, 'artifact-mobile.png') });
  evidence.artifactOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(evidence.artifactOverflow).toBe(false);
  expect(errors).toEqual([]);
  evidence.status = 'passed';
  console.log(JSON.stringify(evidence, null, 2));
} catch (error) {
  evidence.status = 'failed';
  evidence.failure = String(error);
  await page.screenshot({ path: path.join(out, 'browser-failure.png'), fullPage: true });
  throw error;
} finally {
  await fs.writeFile(path.join(out, 'browser.json'), JSON.stringify(evidence, null, 2));
  await browser.close();
}
